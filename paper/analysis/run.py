#!/usr/bin/env python3
"""Regenerate every number, table and figure of the final manuscript from the saved logs.

Usage (from the repository root):
    python3 -m paper.analysis.run

Inputs : data/benchmark.jsonl, data/overlap_audit.json, config.json, outputs/*.jsonl,
         assignment4/error_annotation.csv
Outputs: paper/results/final_results.json   all numbers, keyed as cited in paper/README.md
         paper/results/item_level.csv       sentence-level scores for every analysed response
         paper/generated/numbers.tex        LaTeX macros used in the text (single source of truth)
         paper/generated/tab_*.tex          LaTeX tables
         paper/figures/fig_*.pdf            vector figures

Seed 42 and 1,000 bootstrap resamples, so a rerun reproduces the files byte for byte
(figures aside, whose PDF metadata is fixed below as well).
"""
import csv
import json
import re
import sys
from pathlib import Path

import numpy as np
import sacrebleu
from scipy import stats

from paper.analysis import lib
from paper.analysis import figures

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "paper"
K_PRIMARY = 5          # prefix length for the inflection-tolerant analysis (sensitivity: 3-8)
K_SWEEP = (3, 4, 5, 6, 7, 8)
SHIFT = 69             # mismatched-reference control: pair output i with reference i+69 (half the sample)
DISPLAY = {"gemini-3.5-flash-lite": "Gemini 3.5 Flash-Lite", "qwen2.5-1.5b": "Qwen 2.5 1.5B",
           "gemma3": "Gemma 3", "nllb": "NLLB-200 600M", "dictionary": "Dictionary baseline"}


# --------------------------------------------------------------------------- helpers
def f2(x):
    return f"{x:.2f}"


def ci(d, fmt=f2):
    return f"{fmt(d['point'])} [{fmt(d['lo'])}, {fmt(d['hi'])}]"


def tex_escape(s):
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def macro_name(key):
    """numbers.tex macro names may contain letters only."""
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
              "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    key = "".join(digits.get(c, c) for c in key)
    parts = re.split(r"[^A-Za-z]+", key)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


class Macros:
    def __init__(self):
        self.items = {}

    def add(self, key, value):
        name = macro_name(key)
        if name in self.items:
            raise ValueError(f"duplicate macro {name}")
        self.items[name] = str(value)

    def write(self, path):
        lines = ["% Generated by paper/analysis/run.py from the saved logs. Do not edit by hand."]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.items.items())]
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def pending_models(config):
    names = [m["name"] for m in config["models"]]
    return names + ["nllb"]


# --------------------------------------------------------------------------- main analysis
def main():
    config = json.loads((ROOT / "config.json").read_text())
    bench, prompts, overlap = lib.load_benchmark(ROOT)
    n_prompts = len(prompts)
    M = Macros()
    R = {"seed": lib.SEED, "bootstrap_resamples": lib.N_BOOT, "sacrebleu": sacrebleu.__version__,
         "signatures": lib.signatures()}

    # ---- coverage of every configured system
    outputs, coverage = {}, {}
    for name in pending_models(config):
        out = lib.load_outputs(ROOT / "outputs" / f"{name}.jsonl", prompts)
        outputs[name] = out
        expected = n_prompts if name != "nllb" else sum(p["task"] in ("mt", "probe") for p in prompts)
        coverage[name] = {"saved": len(out), "expected": expected}
    R["coverage"] = coverage
    R["benchmark"] = {"items": len(bench), "prompts_per_model": n_prompts,
                      "tasks": {t: sum(1 for b in bench.values() if b["task"] == t) for t in ("mt", "qa", "probe")}}

    main_model = "gemini-3.5-flash-lite"
    rows = lib.mt_pairs(bench, prompts, outputs[main_model])
    n = len(rows)
    if n == 0:
        sys.exit("No complete translation pairs saved for the main model.")
    idx = lib.boot_indices(n)
    base = lib.dictionary_baseline(rows)
    R["n_pairs"] = n
    R["pairs_sources"] = sorted({r["source"] for r in rows})
    M.add("nPairs", n)
    M.add("nResponses", coverage[main_model]["saved"])
    M.add("nPromptsPerModel", n_prompts)
    M.add("nItems", len(bench))
    M.add("nBoot", f"{lib.N_BOOT:,}")

    # ---- other systems on the matched item set (reported only when complete on these items)
    systems = {main_model: rows, "dictionary": base}
    for name in pending_models(config):
        if name == main_model or not outputs[name]:
            continue
        other = {r["item_id"]: r for r in lib.mt_pairs(bench, prompts, outputs[name])}
        if all(r["item_id"] in other for r in rows):
            systems[name] = [other[r["item_id"]] for r in rows]

    # ---- main table: corpus metrics with 95% CI, gap with paired bootstrap CI
    main_tab = {}
    for sysname, srows in systems.items():
        main_tab[sysname] = {}
        for metric in lib.METRICS:
            seg = {d: lib.segment_stats(srows, d, metric) for d in lib.DIRECTIONS}
            entry = {d: lib.corpus_with_ci(seg[d], idx, metric)[0] for d in lib.DIRECTIONS}
            entry["gap"] = lib.gap_with_ci(seg["en2kk"], seg["kk2en"], idx, metric)
            main_tab[sysname][metric] = entry
    R["main"] = main_tab
    g = main_tab[main_model]
    for metric, tag in (("chrf2", "Chrf"), ("chrfpp", "ChrfPP"), ("bleu", "Bleu"), ("ter", "Ter")):
        for d, dt in (("en2kk", "KK"), ("kk2en", "EN")):
            M.add(f"gem{tag}{dt}", f2(g[metric][d]["point"]))
            M.add(f"gem{tag}{dt}Lo", f2(g[metric][d]["lo"]))
            M.add(f"gem{tag}{dt}Hi", f2(g[metric][d]["hi"]))
        M.add(f"gem{tag}Gap", f2(g[metric]["gap"]["point"]))
        M.add(f"gem{tag}GapAbs", f2(abs(g[metric]["gap"]["point"])))
        M.add(f"gem{tag}GapLo", f2(g[metric]["gap"]["lo"]))
        M.add(f"gem{tag}GapHi", f2(g[metric]["gap"]["hi"]))
    b = main_tab["dictionary"]
    for d, dt in (("en2kk", "KK"), ("kk2en", "EN")):
        M.add(f"dictChrf{dt}", f2(b["chrf2"][d]["point"]))
        M.add(f"dictBleu{dt}", f2(b["bleu"][d]["point"]))
    M.add("dictChrfGap", f2(b["chrf2"]["gap"]["point"]))
    M.add("dictChrfGapLo", f2(b["chrf2"]["gap"]["lo"]))
    M.add("dictChrfGapHi", f2(b["chrf2"]["gap"]["hi"]))
    M.add("gemRelGapPct", f"{100 * abs(g['chrf2']['gap']['point']) / g['chrf2']['kk2en']['point']:.1f}")

    # ---- sentence-level scores and tests (Wilcoxon signed-rank, Holm over three comparisons)
    s = {d: lib.sentence_chrf(rows, d) for d in lib.DIRECTIONS}
    sb = {d: lib.sentence_chrf(base, d) for d in lib.DIRECTIONS}
    tests = {"direction": lib.wilcoxon(s["en2kk"], s["kk2en"]),
             "vs_dict_en2kk": lib.wilcoxon(s["en2kk"], sb["en2kk"]),
             "vs_dict_kk2en": lib.wilcoxon(s["kk2en"], sb["kk2en"])}
    for k, a in zip(tests, lib.holm([t["p"] for t in tests.values()])):
        tests[k]["p_holm"] = a
    R["tests"] = tests
    t = tests["direction"]
    below = int((s["en2kk"] < s["kk2en"]).sum())
    R["items_lower_into_kk"] = below
    M.add("wilW", f"{t['W']:.0f}")
    M.add("wilP", sci(t["p_holm"]))
    M.add("wilR", f"{t['rank_biserial_r']:.2f}")
    M.add("wilMed", f2(t["median_diff"]))
    M.add("itemsBelow", below)
    M.add("itemsBelowPct", f"{100 * below / n:.1f}")

    # ---- sensitivity and subgroup analyses (exploratory)
    def subset_gap(pred, metric="chrf2"):
        sub = [r for r in rows if pred(r)]
        if len(sub) < 10:
            return None
        sidx = lib.boot_indices(len(sub))
        res = lib.gap_with_ci(lib.segment_stats(sub, "en2kk", metric), lib.segment_stats(sub, "kk2en", metric), sidx, metric)
        res["n"] = len(sub)
        res["en2kk"] = lib.score_from_stats(metric, lib.segment_stats(sub, "en2kk", metric).sum(0))
        res["kk2en"] = lib.score_from_stats(metric, lib.segment_stats(sub, "kk2en", metric).sum(0))
        return res

    latin = {r["item_id"]: lib.latin_share(r["hyp_en2kk"]) for r in rows}
    mostly_latin = sorted(i for i, v in latin.items() if v > 0.5)
    any_latin = sorted(i for i, v in latin.items() if v > 0)
    ref_latin = sum(1 for r in rows if lib.latin_share(r["kk"]) > 0)
    R["script"] = {"mostly_latin_outputs": mostly_latin, "outputs_with_any_latin": len(any_latin),
                   "references_with_any_latin": ref_latin}
    M.add("nMostlyLatin", len(mostly_latin))
    M.add("nAnyLatin", len(any_latin))
    M.add("nRefLatin", ref_latin)

    lens = np.array([len(r["en"].split()) for r in rows])
    q1, q2 = np.percentile(lens, [100 / 3, 200 / 3])
    subsets = {
        "all": lambda r: True,
        "no_pilot": lambda r: r["item_id"] not in overlap,
        "no_latin": lambda r: r["item_id"] not in mostly_latin,
    }
    for dom in sorted({r["domain"] for r in rows}):
        subsets[f"domain_{dom}"] = (lambda r, dd=dom: r["domain"] == dd)
    subsets["len_short"] = lambda r: len(r["en"].split()) <= q1
    subsets["len_medium"] = lambda r: q1 < len(r["en"].split()) <= q2
    subsets["len_long"] = lambda r: len(r["en"].split()) > q2
    R["length_cutpoints_words"] = [float(q1), float(q2)]
    sub = {k: subset_gap(f) for k, f in subsets.items()}
    R["subsets"] = sub
    for k in ("no_pilot", "no_latin"):
        tag = "NoPilot" if k == "no_pilot" else "NoLatin"
        M.add(f"gap{tag}", f2(sub[k]["point"]))
        M.add(f"gap{tag}Lo", f2(sub[k]["lo"]))
        M.add(f"gap{tag}Hi", f2(sub[k]["hi"]))
        M.add(f"n{tag}", sub[k]["n"])
    M.add("nPilotOverlap", n - sub["no_pilot"]["n"])
    M.add("lenCutLo", f"{q1:.0f}")
    M.add("lenCutHi", f"{q2:.0f}")
    rho = {d: stats.spearmanr(lens, s[d]) for d in lib.DIRECTIONS}
    R["spearman_length"] = {d: {"rho": float(v.statistic), "p": float(v.pvalue)} for d, v in rho.items()}
    M.add("rhoLenKK", f"{rho['en2kk'].statistic:.2f}")
    M.add("rhoLenEN", f"{rho['kk2en'].statistic:.2f}")

    # ---- inflection-tolerant matching (automatic proxy for suffix-level mismatch)
    infl = {k: lib.near_miss_with_ci(rows, k, idx, SHIFT) for k in K_SWEEP}
    R["inflection"] = {str(k): v for k, v in infl.items()}
    ip = infl[K_PRIMARY]
    M.add("kPrimary", K_PRIMARY)
    M.add("nmKK", pct(ip["en2kk"]["rate"]))
    M.add("nmKKLo", pct(ip["en2kk"]["lo"]))
    M.add("nmKKHi", pct(ip["en2kk"]["hi"]))
    M.add("nmEN", pct(ip["kk2en"]["rate"]))
    M.add("nmENLo", pct(ip["kk2en"]["lo"]))
    M.add("nmENHi", pct(ip["kk2en"]["hi"]))
    M.add("nmCtrlKK", pct(ip["en2kk"]["control_rate"]))
    M.add("nmCtrlEN", pct(ip["kk2en"]["control_rate"]))
    M.add("nmDiff", pct(ip["kk_minus_en"]["point"]))
    M.add("nmDiffLo", pct(ip["kk_minus_en"]["lo"]))
    M.add("nmDiffHi", pct(ip["kk_minus_en"]["hi"]))
    M.add("recallKK", pct(ip["en2kk"]["exact_recall"]))
    M.add("recallEN", pct(ip["kk2en"]["exact_recall"]))
    M.add("nmShareOfMissKK", pct(ip["en2kk"]["rate"] / (1 - ip["en2kk"]["exact_recall"])))
    M.add("nmShareOfMissEN", pct(ip["kk2en"]["rate"] / (1 - ip["kk2en"]["exact_recall"])))

    # ---- ablation: gap after cutting every word to a k-letter prefix in outputs and references
    word = re.compile(r"[^\W\d_]+")

    def trunc(text, k):
        return word.sub(lambda m: m.group(0)[:k], text)

    abl = {}
    for k in (None, 6, 5, 4):
        rr = rows if k is None else [{**r, "hyp_en2kk": trunc(r["hyp_en2kk"], k), "hyp_kk2en": trunc(r["hyp_kk2en"], k),
                                       "kk": trunc(r["kk"], k), "en": trunc(r["en"], k)} for r in rows]
        key = "full" if k is None else f"k{k}"
        abl[key] = {}
        for metric in ("chrf2", "bleu"):
            seg = {d: lib.segment_stats(rr, d, metric) for d in lib.DIRECTIONS}
            abl[key][metric] = {d: lib.score_from_stats(metric, seg[d].sum(0)) for d in lib.DIRECTIONS}
            abl[key][metric]["gap"] = lib.gap_with_ci(seg["en2kk"], seg["kk2en"], idx, metric)
        f1 = {}
        for d in lib.DIRECTIONS:
            tab = lib.inflection_table(rows, d, k or 1)
            m_full, m_k, hl, rl = tab.sum(0)
            m = m_full if k is None else m_k
            f1[d] = float(100 * 2 * m / (hl + rl))
        f1["gap"] = f1["en2kk"] - f1["kk2en"]
        abl[key]["word_f1"] = f1
    R["ablation_truncation"] = abl
    M.add("ablBleuGapFull", f2(abl["full"]["bleu"]["gap"]["point"]))
    M.add("ablBleuGapK", f2(abl[f"k{K_PRIMARY}"]["bleu"]["gap"]["point"]))
    M.add("ablChrfGapK", f2(abl[f"k{K_PRIMARY}"]["chrf2"]["gap"]["point"]))
    M.add("ablFoneGapFull", f2(abl["full"]["word_f1"]["gap"]))
    M.add("ablFoneGapK", f2(abl[f"k{K_PRIMARY}"]["word_f1"]["gap"]))
    red_bleu = 1 - abl[f"k{K_PRIMARY}"]["bleu"]["gap"]["point"] / abl["full"]["bleu"]["gap"]["point"]
    red_f1 = 1 - abl[f"k{K_PRIMARY}"]["word_f1"]["gap"] / abl["full"]["word_f1"]["gap"]
    M.add("ablBleuRedPct", f"{100 * red_bleu:.0f}")
    M.add("ablFoneRedPct", f"{100 * red_f1:.0f}")

    # ---- token usage reported by the API
    tu = lib.token_usage(rows)
    if tu:
        tk, te = tu["en2kk"]["out_tokens"], tu["kk2en"]["out_tokens"]
        ck, ce = tu["en2kk"]["out_chars"], tu["kk2en"]["out_chars"]
        ratio_draws = [tk[i].sum() / te[i].sum() for i in idx]
        tpc_draws = [(tk[i].sum() / ck[i].sum()) / (te[i].sum() / ce[i].sum()) for i in idx]
        item_ratio = tk / te
        rho_tok = stats.spearmanr(item_ratio, s["en2kk"] - s["kk2en"])
        # source-side estimate: prompt = T + a_lang * chars(source), jointly over both directions
        src_k = np.array([len(r["kk"]) for r in rows], float)
        src_e = np.array([len(r["en"]) for r in rows], float)
        X = np.r_[np.c_[np.ones(n), src_e, np.zeros(n)], np.c_[np.ones(n), np.zeros(n), src_k]]
        y = np.r_[tu["en2kk"]["prompt_tokens"], tu["kk2en"]["prompt_tokens"]]
        coef = np.linalg.lstsq(X, y, rcond=None)[0]
        R["tokens"] = {
            "out_token_ratio_kk_en": float(tk.sum() / te.sum()),
            "out_token_ratio_ci": [float(np.percentile(ratio_draws, 2.5)), float(np.percentile(ratio_draws, 97.5))],
            "out_char_ratio_kk_en": float(ck.sum() / ce.sum()),
            "tokens_per_100_chars": {"en2kk": float(100 * tk.sum() / ck.sum()), "kk2en": float(100 * te.sum() / ce.sum())},
            "per_char_premium": float((tk.sum() / ck.sum()) / (te.sum() / ce.sum())),
            "per_char_premium_ci": [float(np.percentile(tpc_draws, 2.5)), float(np.percentile(tpc_draws, 97.5))],
            "median_out_tokens": {"en2kk": float(np.median(tk)), "kk2en": float(np.median(te))},
            "source_regression": {"template_tokens": float(coef[0]), "tokens_per_char_en": float(coef[1]),
                                  "tokens_per_char_kk": float(coef[2]), "ratio": float(coef[2] / coef[1])},
            "spearman_item_ratio_vs_gap": {"rho": float(rho_tok.statistic), "p": float(rho_tok.pvalue)},
            "item_ratio": item_ratio.tolist(),
        }
        T = R["tokens"]
        M.add("tokRatio", f2(T["out_token_ratio_kk_en"]))
        M.add("tokRatioLo", f2(T["out_token_ratio_ci"][0]))
        M.add("tokRatioHi", f2(T["out_token_ratio_ci"][1]))
        M.add("charRatio", f2(T["out_char_ratio_kk_en"]))
        M.add("tokPerCharKK", f"{T['tokens_per_100_chars']['en2kk']:.1f}")
        M.add("tokPerCharEN", f"{T['tokens_per_100_chars']['kk2en']:.1f}")
        M.add("tokCharPrem", f2(T["per_char_premium"]))
        M.add("tokCharPremLo", f2(T["per_char_premium_ci"][0]))
        M.add("tokCharPremHi", f2(T["per_char_premium_ci"][1]))
        M.add("tokSrcRatio", f2(T["source_regression"]["ratio"]))
        M.add("rhoTok", f"{T['spearman_item_ratio_vs_gap']['rho']:.2f}")
        M.add("rhoTokP", f"{T['spearman_item_ratio_vs_gap']['p']:.2f}")

    # ---- request latency (public API path; not a hardware-controlled measurement)
    lat = {d: np.array([r[f"rec_{d}"]["elapsed_seconds"] for r in rows]) for d in lib.DIRECTIONS}
    R["latency"] = {d: {"median": float(np.median(v)), "q1": float(np.percentile(v, 25)), "q3": float(np.percentile(v, 75)),
                        "p95": float(np.percentile(v, 95))} for d, v in lat.items()}
    M.add("latKK", f2(R["latency"]["en2kk"]["median"]))
    M.add("latEN", f2(R["latency"]["kk2en"]["median"]))

    # ---- QA: simple baselines always; models only when both language versions are saved
    fixed, rand = lib.qa_baseline_answers(prompts)
    qa = {"always_a": lib.score_qa(prompts, fixed), "seeded_random": lib.score_qa(prompts, rand)}
    for name in pending_models(config):
        if name == "nllb":
            continue
        ans = {pid: rec.get("output") for pid, rec in outputs[name].items()}
        res = lib.score_qa(prompts, ans)
        qa[name] = res if res["n"] else {"n": 0, "status": "pending"}
    R["qa"] = qa
    gold = [p["gold"] for p in prompts if p["task"] == "qa" and p["condition"] == "qa_en"]
    R["qa_gold_distribution"] = {c: gold.count(c) for c in "ABCD"}
    for key, tag in (("always_a", "QaA"), ("seeded_random", "QaRnd")):
        q = qa[key]
        M.add(f"{tag}KK", f"{100 * q['acc_kk']:.1f}")
        M.add(f"{tag}EN", f"{100 * q['acc_en']:.1f}")
        M.add(f"{tag}P", f"{q['p_mcnemar']:.4f}")
        M.add(f"{tag}KKonly", q["kk_only"])
        M.add(f"{tag}ENonly", q["en_only"])
    M.add("nQa", qa["always_a"]["n"])

    # ---- provisional first-pass labels of the 30 lowest-scoring EN->KK outputs
    lab_path = ROOT / "assignment4/error_annotation.csv"
    if lab_path.exists():
        labels = [r["error_type"] for r in csv.DictReader(open(lab_path, encoding="utf-8"))]
        counts = {k: labels.count(k) for k in sorted(set(labels), key=lambda x: -labels.count(x))}
        R["provisional_labels"] = {"n": len(labels), "counts": counts,
                                   "status": "single unblinded first pass; independent blind annotation pending"}
        M.add("nReviewed", len(labels))
        for k, v in counts.items():
            M.add(f"lab{k}", v)

    # ---- coverage macros
    M.add("covGemini", coverage[main_model]["saved"])
    M.add("covQwen", coverage.get("qwen2.5-1.5b", {}).get("saved", 0))
    M.add("covGemma", coverage.get("gemma3", {}).get("saved", 0))
    M.add("covNLLB", coverage.get("nllb", {}).get("saved", 0))
    M.add("covPct", f"{100 * coverage[main_model]['saved'] / n_prompts:.1f}")

    # ---------------------------------------------------------------- write files
    (OUT / "results").mkdir(exist_ok=True)
    (OUT / "generated").mkdir(exist_ok=True)
    (OUT / "figures").mkdir(exist_ok=True)
    (OUT / "results/final_results.json").write_text(json.dumps(R, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    with open(OUT / "results/item_level.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["item_id", "source", "domain", "pilot_overlap", "en_words", "chrf2_en2kk", "chrf2_kk2en",
                    "chrf2_dict_en2kk", "chrf2_dict_kk2en", "latin_share_en2kk", "out_tokens_en2kk",
                    "out_tokens_kk2en", "latency_en2kk_s", "latency_kk2en_s"])
        for i, r in enumerate(rows):
            w.writerow([r["item_id"], r["source"], r["domain"], int(r["item_id"] in overlap), len(r["en"].split()),
                        round(s["en2kk"][i], 4), round(s["kk2en"][i], 4), round(sb["en2kk"][i], 4),
                        round(sb["kk2en"][i], 4), round(latin[r["item_id"]], 4),
                        tu["en2kk"]["out_tokens"][i] if tu else "", tu["kk2en"]["out_tokens"][i] if tu else "",
                        round(lat["en2kk"][i], 4), round(lat["kk2en"][i], 4)])
    M.write(OUT / "generated/numbers.tex")
    write_tables(R, systems, main_model, coverage)
    figures.make_all(R, rows, s, systems, main_tab, OUT / "figures", main_model)
    print(json.dumps({"pairs": n, "gap_chrf2": main_tab[main_model]["chrf2"]["gap"],
                      "near_miss_k5": ip["kk_minus_en"]}, indent=1))


def sci(p):
    if p >= 0.001:
        return f"{p:.3f}"
    m, e = f"{p:.1e}".split("e")
    return f"{m}\\times10^{{{int(e)}}}"


def pct(x):
    return f"{100 * x:.1f}"


